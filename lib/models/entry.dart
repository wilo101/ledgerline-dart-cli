class Entry {
  Entry(this.id, this.date, this.category, this.note, this.amount, {this.recurringId, this.tags = const []});

  factory Entry.fromJson(Map<String, dynamic> j) => Entry(
        j['id'] as int,
        '${j['date']}',
        '${j['category']}',
        '${j['note'] ?? ''}',
        (j['amount'] as num).toDouble(),
        recurringId: j['recurringId'] as int?,
        tags: ((j['tags'] ?? const []) as List).map((e) => '$e').toList(),
      );

  Map<String, dynamic> toJson() => {
        'id': id,
        'date': date,
        'category': category,
        'note': note,
        'amount': amount,
        if (recurringId != null) 'recurringId': recurringId,
        if (tags.isNotEmpty) 'tags': tags,
      };

  final int id;
  final String date, category, note;

  /// Positive = income, negative = expense.
  final double amount;

  /// Set when the entry was generated by a recurring rule.
  final int? recurringId;
  final List<String> tags;

  bool get isExpense => amount < 0;

  Entry copyWith({String? date, String? category, String? note, double? amount, List<String>? tags}) =>
      Entry(id, date ?? this.date, category ?? this.category, note ?? this.note, amount ?? this.amount,
          recurringId: recurringId, tags: tags ?? this.tags);
}
